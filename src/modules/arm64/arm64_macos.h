// Included in Arm64::init: the macros of the generated program and the
// routines that talk to macOS. Apple keeps the C functions of libSystem
// compatible between releases, not the system calls under them (Technical
// Q&A QA1118), so the routines call those functions.

_head << "// Assemble and link with:\n"
         "//   cc -arch arm64 -x assembler -c -o prog.o prog.s &&\n"
         "//     cc -arch arm64 -o prog prog.o\n"
         "\n"
         "    .equ SIZEOF_SLOT, 8\n"
         "    .equ MEMORY_SIZE, 1048576\n"
         "    .equ BUFFER_SIZE, 1024\n"
         "\n"
         "// Every push takes a 16-byte slot, so that sp stays aligned to\n"
         "// 16 bytes, as the calling convention of the C functions asks.\n"
         ".macro push reg\n"
         "    str \\reg, [sp, #-16]!\n"
         ".endm\n"
         "\n"
         ".macro pop reg\n"
         "    ldr \\reg, [sp], #16\n"
         ".endm\n"
         "\n"
         ".macro begin size\n"
         "    stp x29, x30, [sp, #-16]!\n"
         "    mov x29, sp\n"
         "  .if \\size\n"
         "    sub sp, sp, #\\size\n"
         "  .endif\n"
         ".endm\n"
         "\n"
         ".macro return\n"
         "    mov sp, x29\n"
         "    ldp x29, x30, [sp], #16\n"
         "    ret\n"
         ".endm\n"
         "\n"
         ".macro clargs count\n"
         "    add sp, sp, #16 * \\count\n"
         ".endm\n"
         "\n"
         "// la: load the address of a label anywhere within 4 GiB of the\n"
         "// code.\n"
         ".macro la reg, label\n"
         "    adrp \\reg, \\label\\()@PAGE\n"
         "    add \\reg, \\reg, \\label\\()@PAGEOFF\n"
         ".endm\n"
         "\n"
         ".macro rodata\n"
         "    .pushsection __TEXT,__const\n"
         ".endm\n"
         "\n"
         "// libcall: calls a C function of libSystem, with its arguments in\n"
         "// x0-x5 and its result in x0. The C calling convention lets the\n"
         "// function change x1-x17, d0-d7 and d16-d31, and the rest of the\n"
         "// runtime was written for Linux system calls, which keep them.\n"
         ".macro libcall function\n"
         "    stp x1, x2, [sp, #-336]!\n"
         "    stp x3, x4, [sp, #16]\n"
         "    stp x5, x6, [sp, #32]\n"
         "    stp x7, x8, [sp, #48]\n"
         "    stp x9, x10, [sp, #64]\n"
         "    stp x11, x12, [sp, #80]\n"
         "    stp x13, x14, [sp, #96]\n"
         "    stp x15, x16, [sp, #112]\n"
         "    str x17, [sp, #128]\n"
         "    stp d0, d1, [sp, #144]\n"
         "    stp d2, d3, [sp, #160]\n"
         "    stp d4, d5, [sp, #176]\n"
         "    stp d6, d7, [sp, #192]\n"
         "    stp d16, d17, [sp, #208]\n"
         "    stp d18, d19, [sp, #224]\n"
         "    stp d20, d21, [sp, #240]\n"
         "    stp d22, d23, [sp, #256]\n"
         "    stp d24, d25, [sp, #272]\n"
         "    stp d26, d27, [sp, #288]\n"
         "    stp d28, d29, [sp, #304]\n"
         "    stp d30, d31, [sp, #320]\n"
         "    bl \\function\n"
         "    ldp x3, x4, [sp, #16]\n"
         "    ldp x5, x6, [sp, #32]\n"
         "    ldp x7, x8, [sp, #48]\n"
         "    ldp x9, x10, [sp, #64]\n"
         "    ldp x11, x12, [sp, #80]\n"
         "    ldp x13, x14, [sp, #96]\n"
         "    ldp x15, x16, [sp, #112]\n"
         "    ldr x17, [sp, #128]\n"
         "    ldp d0, d1, [sp, #144]\n"
         "    ldp d2, d3, [sp, #160]\n"
         "    ldp d4, d5, [sp, #176]\n"
         "    ldp d6, d7, [sp, #192]\n"
         "    ldp d16, d17, [sp, #208]\n"
         "    ldp d18, d19, [sp, #224]\n"
         "    ldp d20, d21, [sp, #240]\n"
         "    ldp d22, d23, [sp, #256]\n"
         "    ldp d24, d25, [sp, #272]\n"
         "    ldp d26, d27, [sp, #288]\n"
         "    ldp d28, d29, [sp, #304]\n"
         "    ldp d30, d31, [sp, #320]\n"
         "    ldp x1, x2, [sp], #336\n"
         ".endm\n"
         "\n"
         ".macro exit code\n"
         "    mov w0, \\code\n"
         "    bl _exit\n"
         ".endm\n"
         "\n"
         ".macro print_lf\n"
         "    mov x0, #10\n"
         "    push x0\n"
         "    bl print_c\n"
         "    clargs 1\n"
         ".endm\n";

_lib << "\n"
        "// print_bytes(string, length): writes length bytes to stdout.\n"
        "print_bytes:\n"
        "    begin 0\n"
        "    ldr w2, [x29, #16]\n"
        "    ldr x1, [x29, #32]\n"
        "    mov x0, #1\n"
        "    libcall _write\n"
        "    return\n"
        "\n"
        "print:\n"
        "    begin 0\n"
        "    ldr x0, [x29, #16]\n"
        "    push x0\n"
        "    bl strlen\n"
        "    clargs 1\n"
        "\n"
        "    ldr x1, [x29, #16]\n"
        "    push x1\n"
        "    push x0\n"
        "    bl print_bytes\n"
        "    clargs 2\n"
        "    return\n"
        "\n"
        "print_err:\n"
        "    begin 0\n"
        "    ldr x0, [x29, #16]\n"
        "    push x0\n"
        "    bl strlen\n"
        "    clargs 1\n"
        "\n"
        "    mov w2, w0\n"
        "    ldr x1, [x29, #16]\n"
        "    mov x0, #2\n"
        "    libcall _write\n"
        "    return\n"
        "\n"
        "// readline(buffer, size): reads one line from stdin into buffer,\n"
        "// without the newline and NUL terminated. Bytes beyond size-1 are\n"
        "// consumed and dropped, so the next call starts on the next line.\n"
        "// A read cut short by a signal (errno EINTR, 4) is retried; any\n"
        "// other error ends the line like end of file. Returns the bytes\n"
        "// stored. The count lives at x29-8 and the byte just read at\n"
        "// x29-16.\n"
        "readline:\n"
        "    begin 16\n"
        "    str xzr, [x29, #-8]\n"
        ".Lreadline_next:\n"
        "    mov x0, #0\n"
        "    sub x1, x29, #16\n"
        "    mov x2, #1\n"
        "    libcall _read\n"
        "\n"
        "    cmn x0, #1\n"
        "    b.ne .Lreadline_read\n"
        "    libcall ___error\n"
        "    ldr w0, [x0]\n"
        "    cmp w0, #4\n"
        "    b.eq .Lreadline_next\n"
        "    b .Lreadline_done\n"
        ".Lreadline_read:\n"
        "    cmp x0, #1\n"
        "    b.lt .Lreadline_done\n"
        "    ldrb w3, [x29, #-16]\n"
        "    cmp w3, #10\n"
        "    b.eq .Lreadline_done\n"
        "\n"
        "    ldr w0, [x29, #-8]\n"
        "    add w0, w0, #1\n"
        "    ldr w4, [x29, #16]\n"
        "    cmp w0, w4\n"
        "    b.ge .Lreadline_next\n"
        "    ldr x1, [x29, #32]\n"
        "    ldr w2, [x29, #-8]\n"
        "    strb w3, [x1, w2, uxtw]\n"
        "    str w0, [x29, #-8]\n"
        "    b .Lreadline_next\n"
        "\n"
        ".Lreadline_done:\n"
        "    ldr x1, [x29, #32]\n"
        "    ldr w0, [x29, #-8]\n"
        "    strb wzr, [x1, w0, uxtw]\n"
        "    return\n"
        "\n"
        "// alloc_pages(size): size bytes of zeroed memory from mmap, or 0.\n"
        "// PROT_READ|PROT_WRITE and MAP_PRIVATE|MAP_ANON, which is 0x1000\n"
        "// on macOS. mmap returns -1 when it fails.\n"
        "alloc_pages:\n"
        "    begin 0\n"
        "    mov x0, #0\n"
        "    ldr x1, [x29, #16]\n"
        "    mov x2, #3\n"
        "    mov x3, #0x1002\n"
        "    mov x4, #-1\n"
        "    mov x5, #0\n"
        "    libcall _mmap\n"
        "\n"
        "    cmn x0, #1\n"
        "    b.ne .Lalloc_pages_done\n"
        "    mov x0, #0\n"
        ".Lalloc_pages_done:\n"
        "    return\n";

