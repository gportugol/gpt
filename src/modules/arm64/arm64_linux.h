// Included in Arm64::init: the macros of the generated program and the
// routines that talk to Linux through system calls.

_head << "// Assemble and link with:\n"
         "//   as -o prog.o prog.s && ld -static -e start -o prog prog.o\n"
         "\n"
         "    .equ SIZEOF_SLOT, 8\n"
         "    .equ MEMORY_SIZE, 1048576\n"
         "    .equ BUFFER_SIZE, 1024\n"
         "\n"
         "// Every push takes a 16-byte slot: Linux faults on a load or\n"
         "// store through sp while sp is not aligned to 16.\n"
         ".macro push reg\n"
         "    str \\reg, [sp, #-16]!\n"
         ".endm\n"
         "\n"
         ".macro pop reg\n"
         "    ldr \\reg, [sp], #16\n"
         ".endm\n"
         "\n"
         ".macro begin size\n"
         "    stp x29, x30, [sp, #-16]!\n"
         "    mov x29, sp\n"
         "  .if \\size\n"
         "    sub sp, sp, #\\size\n"
         "  .endif\n"
         ".endm\n"
         "\n"
         ".macro return\n"
         "    mov sp, x29\n"
         "    ldp x29, x30, [sp], #16\n"
         "    ret\n"
         ".endm\n"
         "\n"
         ".macro clargs count\n"
         "    add sp, sp, #16 * \\count\n"
         ".endm\n"
         "\n"
         "// la: load the address of a label anywhere within 4 GiB of the\n"
         "// code.\n"
         ".macro la reg, label\n"
         "    adrp \\reg, \\label\n"
         "    add \\reg, \\reg, :lo12:\\label\n"
         ".endm\n"
         "\n"
         ".macro exit code\n"
         "    mov w0, \\code\n"
         "    mov x8, #93\n"
         "    svc #0\n"
         ".endm\n"
         "\n"
         ".macro print_lf\n"
         "    mov x0, #10\n"
         "    push x0\n"
         "    bl print_c\n"
         "    clargs 1\n"
         ".endm\n";

_lib << "\n"
        "// print_bytes(string, length): writes length bytes to stdout.\n"
        "print_bytes:\n"
        "    begin 0\n"
        "    ldr w2, [x29, #16]\n"
        "    ldr x1, [x29, #32]\n"
        "    mov x0, #1\n"
        "    mov x8, #64\n"
        "    svc #0\n"
        "    return\n"
        "\n"
        "print:\n"
        "    begin 0\n"
        "    ldr x0, [x29, #16]\n"
        "    push x0\n"
        "    bl strlen\n"
        "    clargs 1\n"
        "\n"
        "    ldr x1, [x29, #16]\n"
        "    push x1\n"
        "    push x0\n"
        "    bl print_bytes\n"
        "    clargs 2\n"
        "    return\n"
        "\n"
        "print_err:\n"
        "    begin 0\n"
        "    ldr x0, [x29, #16]\n"
        "    push x0\n"
        "    bl strlen\n"
        "    clargs 1\n"
        "\n"
        "    mov w2, w0\n"
        "    ldr x1, [x29, #16]\n"
        "    mov x0, #2\n"
        "    mov x8, #64\n"
        "    svc #0\n"
        "    return\n"
        "\n"
        "// readline(buffer, size): reads one line from stdin into buffer,\n"
        "// without the newline and NUL terminated. Bytes beyond size-1 are\n"
        "// consumed and dropped, so the next call starts on the next line.\n"
        "// A read cut short by a signal (-EINTR) is retried; any other\n"
        "// error ends the line like end of file. Returns the bytes stored.\n"
        "// The count lives at x29-8 and the byte just read at x29-16.\n"
        "readline:\n"
        "    begin 16\n"
        "    str xzr, [x29, #-8]\n"
        ".Lreadline_next:\n"
        "    mov x0, #0\n"
        "    sub x1, x29, #16\n"
        "    mov x2, #1\n"
        "    mov x8, #63\n"
        "    svc #0\n"
        "\n"
        "    cmn x0, #4\n"
        "    b.eq .Lreadline_next\n"
        "    cmp x0, #1\n"
        "    b.lt .Lreadline_done\n"
        "    ldrb w3, [x29, #-16]\n"
        "    cmp w3, #10\n"
        "    b.eq .Lreadline_done\n"
        "\n"
        "    ldr w0, [x29, #-8]\n"
        "    add w0, w0, #1\n"
        "    ldr w4, [x29, #16]\n"
        "    cmp w0, w4\n"
        "    b.ge .Lreadline_next\n"
        "    ldr x1, [x29, #32]\n"
        "    ldr w2, [x29, #-8]\n"
        "    strb w3, [x1, w2, uxtw]\n"
        "    str w0, [x29, #-8]\n"
        "    b .Lreadline_next\n"
        "\n"
        ".Lreadline_done:\n"
        "    ldr x1, [x29, #32]\n"
        "    ldr w0, [x29, #-8]\n"
        "    strb wzr, [x1, w0, uxtw]\n"
        "    return\n"
        "\n"
        "// alloc_pages(size): size bytes of zeroed memory from mmap, or 0.\n"
        "// PROT_READ|PROT_WRITE and MAP_PRIVATE|MAP_ANONYMOUS.\n"
        "alloc_pages:\n"
        "    begin 0\n"
        "    mov x0, #0\n"
        "    ldr x1, [x29, #16]\n"
        "    mov x2, #3\n"
        "    mov x3, #0x22\n"
        "    mov x4, #-1\n"
        "    mov x5, #0\n"
        "    mov x8, #222\n"
        "    svc #0\n"
        "\n"
        "    cmn x0, #4095\n"
        "    b.lo .Lalloc_pages_done\n"
        "    mov x0, #0\n"
        ".Lalloc_pages_done:\n"
        "    return\n";

